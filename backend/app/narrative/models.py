import re
from typing import Any

from pydantic import BaseModel, Field, field_validator


class NarrativeOutput(BaseModel):
    """Structured narrative output validated against schema."""

    headline: str = Field(description="Exactly one sentence summarizing the top finding.")
    supporting_sentences: list[str] = Field(
        description="Two to four short sentences describing drivers and context.",
        default_factory=list,
    )
    caveats: list[str] = Field(
        default_factory=list,
        description="Caveats, data quality flags, or hypotheses labelled as possibilities.",
    )
    is_fallback: bool = Field(
        default=False,
        description="Whether this summary was generated by the deterministic fallback template.",
    )
    fallback_reason: str | None = Field(
        default=None,
        description="Reason why deterministic fallback was used instead of LLM.",
    )

    @field_validator("supporting_sentences", "caveats", mode="before")
    @classmethod
    def coerce_list(cls, v: Any) -> list[str]:
        if isinstance(v, str):
            items = [s.strip() for s in re.split(r"(?<=[.!?])\s+|\n+", v) if s.strip()]
            return items if items else [v.strip()]
        if isinstance(v, list):
            return [str(item).strip() for item in v if str(item).strip()]
        return []


class TokenUsageLog(BaseModel):
    """Usage and latency record per LLM call."""

    prompt_tokens: int = 0
    completion_tokens: int = 0
    total_tokens: int = 0
    latency_ms: float = 0.0
    model: str = ""
    timestamp: float = 0.0
